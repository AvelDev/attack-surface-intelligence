const DICTS = { pl, en };
const Ctx = createContext(null);

function readLang() {
  try {
    const v = localStorage.getItem("asi.lang");
    if (v === "pl" || v === "en") return v;
  } catch (e) { /* prywatne okno */ }
  return (navigator.language || "pl").toLowerCase().startsWith("pl") ? "pl" : "en";
}

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(readLang);
  const setLang = useCallback((l) => {
    setLangState(l);
    try { localStorage.setItem("asi.lang", l); } catch (e) { /* ignoruj */ }
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
    document.title = DICTS[lang]["app.title"];
  }, [lang]);
  const value = useMemo(() => {
    const dict = DICTS[lang];
    const t = (key, vars) => {
      let s = dict[key] ?? pl[key] ?? key;
      if (vars) for (const k in vars) s = s.split(`{${k}}`).join(String(vars[k]));
      return s;
    };
    const nf = new Intl.NumberFormat(lang === "pl" ? "pl-PL" : "en-GB");
    const df = new Intl.DateTimeFormat(lang === "pl" ? "pl-PL" : "en-GB", { day: "2-digit", month: "2-digit", hour: "2-digit", minute: "2-digit" });
    const dd = new Intl.DateTimeFormat(lang === "pl" ? "pl-PL" : "en-GB", { day: "2-digit", month: "2-digit" });
    const n = (v) => nf.format(v ?? 0);
    const date = (ts) => (ts ? df.format(new Date(ts * 1000)) : "—");
    const day = (ts) => (ts ? dd.format(new Date(ts * 1000)) : "—");
    const ago = (ts) => {
      if (!ts) return t("d.never");
      const s = Date.now() / 1000 - ts;
      if (s < 60) return t("time.now");
      if (s < 3600) return t("time.min", { n: Math.floor(s / 60) });
      if (s < 86400) return t("time.h", { n: Math.floor(s / 3600) });
      return t("time.d", { n: Math.floor(s / 86400) });
    };
    const dur = (sec) => {
      sec = Math.max(0, Math.round(sec || 0));
      const h = Math.floor(sec / 3600), m = Math.floor((sec % 3600) / 60), s = sec % 60;
      if (h) return `${h} h ${String(m).padStart(2, "0")} min`;
      if (m) return `${m} min`;
      return `${s} s`;
    };
    // Dla treści ustaleń typu "builtin" (zob. FINDING_EN) - inne źródła (nuclei/signature)
    // wraca bez zmian, bo nie są naszym tekstem do tłumaczenia.
    const tf = (text) => (lang === "en" ? FINDING_EN[text] || text : text);
    return { lang, setLang, t, tf, n, date, day, ago, dur };
  }, [lang, setLang]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);
